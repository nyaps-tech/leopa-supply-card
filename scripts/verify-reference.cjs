const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const {PNG}=require('pngjs');
const jsQR=require('jsqr');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const images=[...html.matchAll(/data:image\/png;base64,([A-Za-z0-9+/=]+)/g)];
const png=PNG.sync.read(Buffer.from(images.at(-1)[1],'base64'));
const decoded=jsQR(new Uint8ClampedArray(png.data),png.width,png.height);
assert.ok(decoded,'Embedded reference QR must decode independently');
const literal=html.match(/new Blob\(\[("(?:[^"\\]|\\.)*")/)[1];
const download=JSON.parse(literal).replace(/\r?\n/g,'\r\n');
const normalise=text=>text.replace(/\r\n/g,'\n').trim();
assert.equal(normalise(decoded.data),normalise(download),'Embedded QR and Save Contact must have the same fields');
assert.equal(fs.readFileSync(path.join(root,'Blessing_Leopa.vcf'),'utf8'),download,'Static contact download must match the card');
const contact=JSON.parse(fs.readFileSync(path.join(root,'contact.json'),'utf8'));
for(const value of [contact.givenName,contact.familyName,contact.company,contact.title,contact.phone,contact.email,contact.website])assert.ok(download.includes(value));
for(const value of [contact.givenName,contact.familyName,contact.title,contact.phone,contact.email,contact.website])assert.ok(html.includes(value));
console.log('PASS: Supplied embedded QR independently decoded; QR, displayed details and contact downloads match.');
